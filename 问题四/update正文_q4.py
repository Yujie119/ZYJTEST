def insert_after(marker: str, text: str) -> None:
    global s
    if text.strip() in s:
        return
    if marker not in s:
        raise SystemExit(f"marker not found: {marker[:60]}")
    s = s.replace(marker, marker + text, 1)

def replace_line(prefix: str, replacement: str) -> None:
    global s
    lines = s.splitlines()
    for i, line in enumerate(lines):
        if line.startswith(prefix):
            lines[i] = replacement
            s = "\n".join(lines) + ("\n" if s.endswith("\n") else "")
            return
    raise SystemExit(f"line not found: {prefix[:80]}")

